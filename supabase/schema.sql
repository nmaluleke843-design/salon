## Supabase schema

```sql
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text check (role in ('client', 'owner', 'agent')) not null default 'client',
  created_at timestamptz default now()
);

create table public.salons (
  id bigint generated by default as identity primary key,
  owner_id uuid references public.profiles(id),
  name text not null,
  category text,
  location text,
  description text,
  rating numeric(2,1) default 0,
  active boolean default true,
  created_at timestamptz default now()
);

create table public.services (
  id bigint generated by default as identity primary key,
  salon_id bigint references public.salons(id) on delete cascade,
  name text not null,
  price numeric(10,2) not null,
  duration_minutes integer not null
);

create table public.bookings (
  id bigint generated by default as identity primary key,
  client_id uuid references public.profiles(id),
  salon_id bigint references public.salons(id),
  service_id bigint references public.services(id),
  status text check (status in ('pending','confirmed','completed','cancelled')) default 'pending',
  appointment_at timestamptz not null,
  created_at timestamptz default now()
);

create table public.commissions (
  id bigint generated by default as identity primary key,
  booking_id bigint references public.bookings(id),
  agent_id uuid references public.profiles(id),
  service_amount numeric(10,2) not null,
  commission_amount numeric(10,2) not null,
  status text check (status in ('pending','paid')) default 'pending',
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;
alter table public.salons enable row level security;
alter table public.services enable row level security;
alter table public.bookings enable row level security;
alter table public.commissions enable row level security;

create policy "public can view active salons" on public.salons for select using (active = true);
create policy "profiles are readable by owner" on public.profiles for select using (auth.uid() = id);
create policy "users can update own profile" on public.profiles for update using (auth.uid() = id);
create policy "clients create bookings" on public.bookings for insert with check (auth.uid() = client_id);
create policy "participants view bookings" on public.bookings for select using (auth.uid() = client_id);
```
